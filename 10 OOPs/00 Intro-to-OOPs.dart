OOPs in Dart :-
              --> Object Oriented Programming (OOPs) is a programming method that  uses objects and their interactions to design and program applications .

              --> In OOP, an object can be anything, such as a person, a bank account, a car, or a house. Each object has its attributes (or properties) and behavior (or methods).

              --> For example, a person object may have the attributes name, age and height, and the behavior walk and talk.

(*) Advantage of OOPs:- The some advantages of OOPs are as follows

              --> It is easy to understand and use.
              --> It increases reusability and decreases complexity.
              --> The productivity of programmers increases.
              --> It makes the code easier to maintain, modify and debug.
              --> It promotes teamwork and collaboration.
              --> It reduces the repetition of code.

(*) Features of OOPs:-
                  (1) Class
                  (2) Object 
                  (3) Encapsulation
                  (4) Inheritance 
                  (5) Polymorphism
                  (6) Abstraction

Note: The main purpose of OOP is to break complex problems into smaller objects. 
