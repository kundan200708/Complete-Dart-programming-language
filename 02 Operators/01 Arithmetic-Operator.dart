/*
(1) Arithmetic Operator:-
                        --> Arithmetic operators are commonly used o int and double to build numerical expressions.

                        --> It may also used in somewhere else ,as it happens with operator (+) to concatenate two strings.

                        --> They perform basic mathematical calculations.
                        
The common arihtmetic operators are as follows:-
                        
  + -> addition
  - -> subtraction
  * -> multiplication
  / -> division
  % -> reminder(modulo)
 ~/ -> Integer division return integer


 */

// import 'dart:io';

void main() {
  int? a = 50;
  int? b = 40;
  print(a + b); //90
  print(a - b); //10
  print(a * b); //2000
  print(a / b); //1.25
  print(a % b); //10
  print(a ~/ b); //1
}
